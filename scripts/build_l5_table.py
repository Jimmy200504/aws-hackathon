def build() -> dict:
    groups: list[dict] = []

    def add(source: dict[str, list[str]], kind: str) -> None:
        for surface, districts in source.items():
            if not districts:
                # An entry with no defensible district assignment, kept in the
                # source as a note that it was considered and rejected.
                continue
            groups.append(
                {
                    "id": f"L5/{surface}",
                    "surface": surface,
                    "kind": kind,
                    "districts": districts,
                    "counties": sorted({d.split("/", 1)[0] for d in districts}),
                }
            )

    add(TAIPEI_METRO, "metro_station")
    add(LRT, "lrt_station")
    add(AIRPORT_MRT, "metro_station")
    add(KAOHSIUNG_METRO, "metro_station")
    add(TAICHUNG_METRO, "metro_station")
    add(HSR, "hsr_station")
    add(TRA, "tra_station")
    add(PARKS, "industrial_park")
    add(LANDMARKS, "landmark")
    add(ROADS, "arterial_road")

    # Two sources can legitimately name the same surface (南科 is both a park and
    # a TRA station). Merge rather than emit duplicates.
    merged: dict[str, dict] = {}
    for entry in groups:
        existing = merged.get(entry["surface"])
        if existing is None:
            merged[entry["surface"]] = entry
            continue
        existing["districts"] = sorted(set(existing["districts"]) | set(entry["districts"]))
        existing["counties"] = sorted({d.split("/", 1)[0] for d in existing["districts"]})
        existing["kind"] = f"{existing['kind']}+{entry['kind']}"

    entries = sorted(merged.values(), key=lambda row: row["surface"])
    return {
        "schema": "skillweave-geo-l5-table-v1",
        "provenance": "authored",
        "status": "unvalidated source; scripts/validate_l5_table.py decides what is published",
        "note": (
            "Authored geography is confidently wrong more often than it is "
            "uncertain, so nothing here is trusted until the corpus supports it. "
            "The validator measures where each surface actually occurs in job "
            "text and publishes only what clears the county concentration gate."
        ),
        "kinds": sorted({entry["kind"] for entry in entries}),
        "counts": {
            kind: sum(1 for entry in entries if entry["kind"] == kind)
            for kind in sorted({entry["kind"] for entry in entries})
        },
        "total": len(entries),
        "entries": entries,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    payload = build()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(json.dumps({"total": payload["total"], "counts": payload["counts"]}, ensure_ascii=False, indent=2))
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
