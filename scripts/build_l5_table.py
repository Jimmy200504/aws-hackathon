#!/usr/bin/env python3
"""Author the L5 landmark table, then let the corpus decide what gets published.

`docs/geo-graph.md` L5 covers named places that are not administrative units:
science parks, industrial zones, rail and metro stations, arterial roads and
well-known landmarks. None of it is derivable from the dataset - the search log
carries codes, not names - so it has to be written down, and written-down
geography is exactly the kind of thing that is confidently wrong.

The source data below is authored. It is not the output. `scripts/validate_l5_table.py`
scans the job corpus for every surface and reports where it actually occurs, and
only entries whose measured county concentration clears the gate are published.
Two failure modes are caught that way:

  invented         a station or park that does not exist gets no corpus support
  misassigned      a real place put in the wrong county shows up as a mismatch

A third is not caught by the county gate and is checked separately: a real place
in the right county but the wrong district. For those the validator cross-checks
which L4 districts the same postings resolve to, where that evidence exists.

Entries are deliberately conservative about `districts`. An arterial road runs
through several, and claiming one would be worse than claiming all of them.
"""
